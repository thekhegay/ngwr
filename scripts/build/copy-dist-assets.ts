/**
 * Copies repository-level publishing assets (README, LICENSE, llms.txt, the
 * generated llms-full.txt and the generated `skills/` tree) into the lib's
 * build output so `dist/lib` is publish-ready out of the box. The two
 * `llms*.txt` files ship an agent/LLM quick-ref, and `skills/ngwr/` ships the
 * agent skill, so tools that install ngwr can orient themselves straight from
 * `node_modules/ngwr` — no network, no docs site.
 *
 * Wired into the `build:lib` script so local builds and CI produce the same
 * tarball — no separate "copy" step needed in the publish workflow.
 *
 * Usage:
 *   pnpm tsx scripts/build/copy-dist-assets.ts
 */

import { resolve } from 'node:path';

import { copyInto } from '../lib/fs/copy-into';
import { DIST_LIB_PATH, requireBuiltLib } from '../lib/paths/dist-lib';
import { ROOT_PATH } from '../lib/paths/root';

const ASSETS = ['README.md', 'LICENSE', 'llms.txt', 'llms-full.txt'] as const;

requireBuiltLib('copy-dist-assets');

/**
 * Directories copied whole. `skills/` is generated by `gen/ai-assets.ts`, which
 * is why `build:lib` runs the generator before this script rather than after.
 *
 * It is NOT gitignored, and the difference matters: `skills/ngwr/**` is tracked,
 * so a build's regenerated output is a diff to commit like any other. Believing
 * otherwise is what let the committed skill sit two entry points stale through a
 * whole release — every check reads the freshly built copy, never the one in the
 * repository. Only `llms-full.txt` above is build output nobody commits.
 */
const ASSET_DIRS = ['skills'] as const;

for (const name of ASSETS) {
  copyInto(resolve(ROOT_PATH, name), resolve(DIST_LIB_PATH, name), { label: name, optional: true });
}

for (const name of ASSET_DIRS) {
  copyInto(resolve(ROOT_PATH, name), resolve(DIST_LIB_PATH, name), {
    label: `${name}/`,
    optional: true,
    hint: 'run scripts/gen/ai-assets.ts first.',
  });
}
